import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const elements=new Map(),calls=[];let paints=0,failConfig=false;
const el=id=>{if(!elements.has(id))elements.set(id,{textContent:'',disabled:true,attrs:{},setAttribute(k,v){this.attrs[k]=v},toggleAttribute(k,yes){if(yes)this.attrs[k]='';else delete this.attrs[k]}});return elements.get(id)};
const calibration={phase:'idle',guide:null,review:{corner_target:null},target:null,has_frame:false,camera_closed:true,saved:false};
const config={run_id:'calibration',calibration,active:true,terminal_ready:false,camera_opened:false,system_input:false};
const context=vm.createContext({document:{getElementById:el},AbortSignal:{timeout:()=>null},setTimeout:()=>{},
 requestAnimationFrame:callback=>{paints++;callback()},fetch:async(path,options)=>{
 calls.push({path,body:options?.body&&JSON.parse(options.body),paints});
 if(path==='/provider/config'){if(failConfig)throw Error('Listener unavailable');return {ok:true,json:async()=>structuredClone(config)}};
 assert.equal(JSON.parse(options.body).run_id,'calibration');return {ok:true};
 }});
vm.runInContext(fs.readFileSync('tools/provider_calibration.html','utf8').split('<script>')[1].split('</script>')[0],context);
await new Promise(setImmediate);
assert.deepEqual(calls.map(c=>c.path),['/provider/config']);
assert.equal(el('start').disabled,false);assert.equal(el('save').disabled,true);
await el('start').onclick();assert.equal(calls.at(-1).path,'/provider/prepare');
calibration.phase='waiting';calibration.camera_closed=false;calibration.guide={phase:'waiting',step:0,remaining_ms:null,instruction:'Upper left'};
await vm.runInContext('poll()',context);assert(!calls.some(c=>c.path.endsWith('/step')),'No step clock before a source frame');
assert.equal(el('instruction').textContent,'Preparing calibration');
assert.match(el('clock').textContent,/Waiting for first tracking frame/);
assert.match(el('progress').textContent,/timer starts when/);
assert.match(el('message').textContent,/Wait for tracking to begin/);
assert.equal(el('cancel').disabled,false);
config.camera_opened=true;
await vm.runInContext('poll()',context);
assert.match(el('state').textContent,/Camera open.*Waiting for tracking/);
assert(!calls.some(c=>c.path.endsWith('/step')),'An open device is not a captured frame');
calibration.has_frame=true;config.camera_opened=true;
await vm.runInContext('poll()',context);
assert.equal(el('instruction').textContent,'Upper left');
assert.equal(calls.at(-1).path,'/provider/calibration/step');assert.equal(calls.at(-1).body.step,0);assert.equal(paints,2);
await vm.runInContext('poll()',context);assert.equal(calls.filter(c=>c.path.endsWith('/step')).length,1,'Do not repeat a step acknowledgment');
calibration.guide.step=2;calibration.review.corner_target=[1,0];calibration.target=[.9,.1];
await vm.runInContext('poll()',context);
assert.equal(calls.at(-1).body.step,2);assert.equal(paints,4);
assert.equal(el('corner').attrs.cx,100);assert(!('hidden' in el('corner').attrs));
assert.equal(el('point').attrs.cy,10);assert(!('hidden' in el('point').attrs));
failConfig=true;await vm.runInContext('poll()',context);
assert.match(el('state').textContent,/Camera state unavailable/);assert.equal(el('save').disabled,true);
failConfig=false;
calibration.phase='complete';calibration.guide.phase='complete';calibration.guide.remaining_ms=0;
await vm.runInContext('poll()',context);assert.equal(el('save').disabled,true,'Completion is not camera closure');
calibration.camera_closed=true;config.camera_opened=false;
await vm.runInContext('poll()',context);assert.equal(el('save').disabled,false);
const before=calls.filter(c=>c.path==='/provider/prepare').length;
await el('retry').onclick();assert.equal(calls.at(-1).path,'/provider/calibration/retry');
assert.equal(calls.filter(c=>c.path==='/provider/prepare').length,before,'Retry cannot request acquisition');
calibration.phase='idle';calibration.guide=null;calibration.target=null;calibration.review.corner_target=null;
await vm.runInContext('poll()',context);assert.equal(el('start').disabled,false);assert('hidden' in el('point').attrs);
calibration.phase='complete';calibration.guide={phase:'complete',step:5,instruction:'Verified'};
await vm.runInContext('poll()',context);await el('save').onclick();assert.equal(calls.at(-1).path,'/provider/calibration/save');
